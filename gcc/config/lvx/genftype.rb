require 'optparse'

builtins_file = 'lvx-builtins.def'
output_file = STDOUT

OptionParser.new do |opts|
  opts.banner = "Usage: genftype.rb [file1 [file2 ...]] -o ofile\n" \
    "Reads stdin when no files are given"

  opts.on("-o", "--output FILE", "The output file. Defaults to stdout.") do |f|
    output_file = f
    end

  opts.on_tail("-h", "--help", "Show this message") do
    puts opts
    exit
  end
end.parse!

ARGV << builtins_file if ARGV.empty?

table = []
ARGF.readlines.each do |line|
  if line =~ /([^ ]*FTYPE[^,]*,[^,]*)/
    args, *varargs = $1.split(',').map { |t| t.gsub(/_FTYPE_?/, '_').split('_').map(&:strip) }
    varargs = varargs.flatten
    table << "DEF_LVX_FTYPE (#{args.size - 1}, (#{args.join(', ')}))"
    unless varargs.empty?
      full_args = args + varargs
      table << "DEF_LVX_FTYPE (#{full_args.size - 1}, (#{full_args.join(', ')}))"
    end
  end
end

out = STDOUT
out = File.open(output_file, 'w') unless output_file == STDOUT

out.puts <<-HEADER
/* Generated by genftype.rb -*- buffer-read-only: t -*- vi:set ro: */

/* lvx-ftypes.def -- List of the compiler builtins types of the LVX backend.

   Copyright (C) 1991-2024 Free Software Foundation, Inc.
